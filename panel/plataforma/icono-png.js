const TABLA_CRC = (() => {
  const t = [];
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = TABLA_CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function trozo(tipo, datos) {
  const largo = Buffer.alloc(4); largo.writeUInt32BE(datos.length);
  const td = Buffer.concat([Buffer.from(tipo, 'ascii'), datos]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
  return Buffer.concat([largo, td, crc]);
}

// color: "#rrggbb" (ya validado). letra: un carácter. tam: lado en píxeles.
function pngIcono({ color, letra, tam }) {
  const h = String(color || '#0c1a2e');
  const r = parseInt(h.slice(1, 3), 16), g = parseInt(h.slice(3, 5), 16), b = parseInt(h.slice(5, 7), 16);
  const px = Buffer.alloc(tam * tam * 3);
  for (let i = 0; i < tam * tam; i++) { px[i * 3] = r; px[i * 3 + 1] = g; px[i * 3 + 2] = b; }

  const glifo = FUENTE[String(letra || '').charAt(0).toUpperCase()];
  if (glifo) {
    const escala = Math.max(1, Math.floor((tam * 0.5) / 7)); // la letra ocupa la mitad del alto
    const x0 = Math.round((tam - 5 * escala) / 2), y0 = Math.round((tam - 7 * escala) / 2);
    for (let fy = 0; fy < 7; fy++) for (let fx = 0; fx < 5; fx++) {
      if (glifo[fy][fx] !== '#') continue;
      for (let dy = 0; dy < escala; dy++) for (let dx = 0; dx < escala; dx++) {
        const i = ((y0 + fy * escala + dy) * tam + (x0 + fx * escala + dx)) * 3;
        px[i] = 255; px[i + 1] = 255; px[i + 2] = 255;
      }
    }
  }

  // Cada fila empieza con el byte de filtro 0 (sin filtro).
  const filas = Buffer.alloc((tam * 3 + 1) * tam);
  for (let y = 0; y < tam; y++) px.copy(filas, y * (tam * 3 + 1) + 1, y * tam * 3, (y + 1) * tam * 3);

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(tam, 0); ihdr.writeUInt32BE(tam, 4);
  ihdr[8] = 8; ihdr[9] = 2; // 8 bits por canal, RGB
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    trozo('IHDR', ihdr),
    trozo('IDAT', zlib.deflateSync(filas)),
    trozo('IEND', Buffer.alloc(0))
  ]);
}

